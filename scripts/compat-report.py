"""Render docs/COMPATIBILITY.md from a self-test report (reports/selftest.json).

Usage: compat-report.py reports/selftest.json > docs/COMPATIBILITY.md
"""
import json
import sys

MARK = {"pass": "✅", "fail": "❌", "skip": "–", "known": "⚠️"}
TITLES = {"od": "Object Dictionary of the shared EDS (master → device)", "sdo": "SDO (master → device)",
          "nmt": "NMT and heartbeat (master → device)", "emcy": "EMCY (consumer ← producer)",
          "pdo": "PDO and SYNC (master → device)", "eds": "EDS/DCF checkers"}


def main():
    doc = json.load(open(sys.argv[1]))
    res = doc["results"]
    out = []
    w = out.append
    counts = doc["counts"]
    w("# Compatibility\n")
    w("Generated by `scripts/compat-report.py` from the self-test report of %s "
      "(Linux %s). %s.\n" % (doc["started"], doc["kernel"],
                             ", ".join("%d %s" % (v, k) for k, v in sorted(counts.items()))))
    w("✅ pass · ❌ fail · ⚠️ known difference ([tests/known-differences.tsv](../tests/known-differences.tsv)) · "
      "– skipped: a stack lacks the capability (never counted as a pass).\n")
    w("## Images\n")
    w("| Adapter | Upstream | Version | Revision |\n|---|---|---|---|")
    for a, v in sorted(doc["versions"].items()):
        w("| %s | %s | %s | `%s` |" % (a, v.get("upstream", ""), v.get("version", ""), v.get("revision", "")[:12]))
    w("")
    for suite, title in TITLES.items():
        rows = [r for r in res if r["suite"] == suite and r["master"] and r["device"]]
        if not rows:
            continue
        pairs = sorted({(r["master"], r["device"]) for r in rows})
        scenarios = []
        for r in rows:
            if r["scenario"] not in scenarios:
                scenarios.append(r["scenario"])
        w("## %s\n" % title)
        w("| Scenario | " + " | ".join("%s → %s" % p for p in pairs) + " |")
        w("|---|" + "---|" * len(pairs))
        for sc in scenarios:
            cells = []
            for p in pairs:
                m = [r for r in rows if r["scenario"] == sc and (r["master"], r["device"]) == p]
                cells.append(" ".join(MARK[r["status"]] for r in m) if m else "")
            w("| %s | %s |" % (sc, " | ".join(cells)))
        w("")
    other = [r for r in res if not (r["master"] and r["device"]) or r["status"] in ("known",)]
    w("## Single-stack scenarios, skips and known differences\n")
    w("| Suite | Scenario | Stacks | Result | Detail |\n|---|---|---|---|---|")
    for r in other:
        stacks = " → ".join(x for x in (r["master"], r["device"]) if x)
        w("| %s | %s | %s | %s | %s |" % (r["suite"], r["scenario"], stacks, MARK[r["status"]],
                                          r["detail"].replace("|", "\\|")[:200]))
    w("")
    fails = [r for r in res if r["status"] == "fail"]
    if fails:
        w("## Failures\n")
        for r in fails:
            w("* %s %s %s → %s: %s" % (r["suite"], r["scenario"], r["master"], r["device"], r["detail"][:300]))
        w("")
    print("\n".join(out))


if __name__ == "__main__":
    main()
