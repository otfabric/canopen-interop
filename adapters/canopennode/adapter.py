def lines_of(stream, sink):
    for raw in iter(stream.readline, b""):
        sink.put(raw.decode("utf-8", "replace").rstrip("\r\n"))
    sink.put(None)


# ── master: canopend and its ASCII gateway ──────────────────────────────────

class Gateway:
    """canopend (example OD, node-ID 0x7F) with the CiA 309-3 gateway on a
    local socket; its log (stderr) is kept as lines for the consumers."""

    def __init__(self, args):
        self.deadline = coi.Deadline(args.timeout_ms)
        self.path = "/tmp/coi-gateway-%d.sock" % os.getpid()
        self.log = queue.Queue()
        self.proc = subprocess.Popen(
            ["canopend", args.interface, "-i", str(MASTER_NODE_ID), "-c", "local-" + self.path],
            stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, cwd="/tmp")
        threading.Thread(target=lines_of, args=(self.proc.stderr, self.log), daemon=True).start()
        self.sock = None
        while self.sock is None:
            if self.proc.poll() is not None:
                raise coi.internal("canopend ended (exit %d): %s" % (self.proc.returncode, self.drain_log()))
            if self.deadline.expired():
                raise coi.timeout("canopend gateway socket not ready")
            try:
                s = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
                s.connect(self.path)
                self.sock = s
            except OSError:
                time.sleep(0.02)
        self.buf = b""
        self.seq = 0

    def drain_log(self):
        out = []
        while True:
            try:
                line = self.log.get_nowait()
            except queue.Empty:
                break
            if line is not None:
                out.append(line)
        return " | ".join(out[-5:])

    def command(self, text):
        """Send one command; return the response after "[seq] ". Comment
        lines ("# ...") before it are kept in self.comments."""
        self.seq += 1
        self.sock.sendall(("[%d] %s\r\n" % (self.seq, text)).encode())
        prefix = "[%d]" % self.seq
        self.comments = []
        while True:
            while b"\n" in self.buf:
                line, self.buf = self.buf.split(b"\n", 1)
                line = line.decode("utf-8", "replace").strip()
                if line.startswith(prefix):
                    return line[len(prefix):].strip()
                if line.startswith("#"):
                    self.comments.append(line)
            remaining = self.deadline.remaining()
            if remaining <= 0:
                raise coi.timeout("no gateway response to: %s" % text[:60])
            self.sock.settimeout(remaining)
            try:
                chunk = self.sock.recv(65536)
            except socket.timeout:
                raise coi.timeout("no gateway response to: %s" % text[:60])
            if not chunk:
                raise coi.internal("gateway closed the connection: %s" % self.drain_log())
            self.buf += chunk

    def ok(self, text):
        resp = self.command(text)
        if resp != "OK":
            raise_gateway_error(resp, text)

    def close(self):
        if self.sock is not None:
            self.sock.close()
        if self.proc.poll() is None:
            self.proc.send_signal(signal.SIGTERM)
            try:
                self.proc.wait(5)
            except subprocess.TimeoutExpired:
                self.proc.kill()
        try:
            os.unlink(self.path)
        except OSError:
            pass


def raise_gateway_error(resp, what):
    m = re.match(r"ERROR:\s*(0x[0-9A-Fa-f]+|\d+)\s*(?:#\s*(.*))?", resp)
    if not m:
        raise coi.internal("unexpected gateway response to %s: %s" % (what[:60], resp[:200]))
    code, desc = m.group(1), (m.group(2) or "").strip()
    if code.lower().startswith("0x"):
        abort = int(code, 16)
        if abort == coi.ABORT_TIMEOUT:
            raise coi.AdapterError(coi.EXIT_TIMEOUT, "timeout", "SDO timeout (%s)" % desc, abortCode="0x%08X" % abort)
        raise coi.sdo_abort(abort, "SDO abort 0x%08X: %s" % (abort, desc))
    raise coi.protocol_error("gateway error %s: %s" % (code, desc))


def with_gateway(args, fn):
    gw = Gateway(args)
    try:
        gw.ok("set sdo_timeout %d" % max(100, min(args.timeout_ms, 60000)))
        return fn(gw)
    finally:
        gw.close()


def cmd_sdo_upload(args, caps):
    def run(gw):
        if args.block:
            gw.ok("set sdo_block 1")
        resp = gw.command("%d r 0x%04X %d hex" % (args.node_id, args.index, args.subindex))
        if resp.startswith("ERROR"):
            raise_gateway_error(resp, "read")
        text = resp.replace(" ", "")
        try:
            return bytes.fromhex(text)
        except ValueError:
            raise coi.internal("gateway response is not hex: %s" % resp[:200])

    data = with_gateway(args, run)
    coi.emit(coi.result("sdo-upload", node=args.node_id, index=coi.hex_index(args.index),
                        subindex=args.subindex, block=args.block, size=len(data), data=data.hex()))


def cmd_sdo_download(args, caps):
    if not args.data:
        raise coi.unsupported("the gateway cannot download 0 bytes")

    def run(gw):
        if args.block:
            gw.ok("set sdo_block 1")
        gw.ok("%d w 0x%04X %d hex %s" % (args.node_id, args.index, args.subindex, args.data.hex()))

    with_gateway(args, run)
    coi.emit(coi.result("sdo-download", node=args.node_id, index=coi.hex_index(args.index),
                        subindex=args.subindex, block=args.block, size=len(args.data)))


def cmd_nmt(args, caps):
    with_gateway(args, lambda gw: gw.ok("%d %s" % (args.node_id, NMT_GATEWAY[args.command])))
    coi.emit(coi.result("nmt", node=args.node_id, command=args.command))


# ── master: LSS (CiA 305) through the gateway ───────────────────────────────

RE_ADDR = re.compile(r"0x([0-9A-Fa-f]{8}) 0x([0-9A-Fa-f]{8}) 0x([0-9A-Fa-f]{8}) 0x([0-9A-Fa-f]{8})")
RE_ASSIGNED = re.compile(r"# Node-ID (\d+) assigned to: " + RE_ADDR.pattern)
INQUIRE_SUB = {"vendor-id": 0, "product-code": 1, "revision": 2, "serial": 3}


def lss_command(gw, step, text):
    """One LSS gateway command; the response or the contract's error."""
    resp = gw.command(text)
    m = re.match(r"ERROR:\s*(\d+)", resp)
    if not m:
        return resp
    code = int(m.group(1))
    if code == 103:
        raise coi.lss_timeout(step, "LSS %s: no response (gateway %s)" % (step, resp))
    if code in (501, 502, 503, 504):
        # CANopenNode's LSS master reports the slave's error code only as
        # "not supported" (1..254) or manufacturer-specific (255).
        raise coi.protocol_error("LSS %s: the slave rejected the request (gateway %s)" % (step, resp), step=step)
    raise coi.protocol_error("LSS %s: gateway %s" % (step, resp), step=step)


def lss_ok(gw, step, text):
    resp = lss_command(gw, step, text)
    if resp != "OK":
        raise coi.internal("unexpected gateway response to %s: %s" % (text, resp[:200]))


def cmd_lss(args, caps):
    """Every step is a command of CANopenNode's CiA 309-3 gateway (LSS master
    CO_LSSmaster): lss_switch_glob, lss_switch_sel, lss_set_node,
    lss_conf_bitrate, lss_activate_bitrate, lss_store, lss_inquire_addr,
    lss_get_node, _lss_fastscan, lss_allnodes."""
    def run(gw):
        for name, arg in args.step:
            if name == "switch-global":
                lss_ok(gw, name, "lss_switch_glob %d" % (arg == "configuration"))
                coi.emit(coi.lss_event(name, mode=arg))
            elif name == "switch-selective":
                lss_ok(gw, name, "lss_switch_sel 0x%08X 0x%08X 0x%08X 0x%08X" % arg)
                coi.emit(coi.lss_event(name, address=coi.lss_address(*arg)))
            elif name == "configure-node-id":
                lss_ok(gw, name, "lss_set_node %d" % arg)
                coi.emit(coi.lss_event(name, node=arg))
            elif name == "configure-bit-timing":
                lss_ok(gw, name, "lss_conf_bitrate 0 %d" % arg)
                coi.emit(coi.lss_event(name, tableIndex=arg, kbps=coi.BIT_TIMING[arg]))
            elif name == "activate-bit-timing":
                lss_ok(gw, name, "lss_activate_bitrate %d" % arg)
                coi.emit(coi.lss_event(name, delayMs=arg))
            elif name == "store":
                lss_ok(gw, name, "lss_store")
                coi.emit(coi.lss_event(name))
            elif name == "inquire":
                if arg == "node-id":
                    resp = lss_command(gw, name, "lss_get_node")
                    m = re.fullmatch(r"0x([0-9A-Fa-f]{1,2})", resp)
                    if not m:
                        raise coi.internal("unexpected gateway response to lss_get_node: %s" % resp[:200])
                    coi.emit(coi.lss_event(name, what=arg, node=int(m.group(1), 16)))
                else:
                    resp = lss_command(gw, name, "lss_inquire_addr %d" % INQUIRE_SUB[arg])
                    m = re.fullmatch(r"0x([0-9A-Fa-f]{8})", resp)
                    if not m:
                        raise coi.internal("unexpected gateway response to lss_inquire_addr: %s" % resp[:200])
                    coi.emit(coi.lss_event(name, what=arg, value="0x%08X" % int(m.group(1), 16)))
            elif name == "fastscan":
                resp = lss_command(gw, name, "_lss_fastscan %d" % LSS_SCAN_TIMEOUT_MS)
                m = RE_ADDR.fullmatch(resp)
                if not m:
                    raise coi.internal("unexpected gateway response to _lss_fastscan: %s" % resp[:200])
                coi.emit(coi.lss_event(name, address=coi.lss_address(*(int(g, 16) for g in m.groups()))))
            elif name == "assign-all":
                first, store = arg
                lss_ok(gw, name, "lss_allnodes %d %d %d" % (LSS_SCAN_TIMEOUT_MS, first, int(store)))
                assigned = []
                for line in gw.comments:
                    m = RE_ASSIGNED.match(line)
                    if m:
                        assigned.append({"node": int(m.group(1)),
                                         "address": coi.lss_address(*(int(g, 16) for g in m.groups()[1:]))})
                coi.emit(coi.lss_event(name, assigned=assigned, store=store))

    with_gateway(args, run)
    coi.emit(coi.result("lss", steps=len(args.step)))


# Time the master waits for an LSS identify slave answer while scanning.
LSS_SCAN_TIMEOUT_MS = 100


def cmd_listen(args, caps):
    """canopend's heartbeat consumer (0x1016 sub 1, configured by a local SDO
    write) and EMCY consumer, as they report in canopend's log."""
    received = 0

    def run(gw):
        nonlocal received
        # consumer heartbeat time: node-ID << 16 | 65535 ms
        gw.ok("%d w 0x1016 1 u32 0x%08X" % (MASTER_NODE_ID, args.node_id << 16 | 0xFFFF))
        coi.emit(coi.event("ready"))
        while received < args.count:
            remaining = gw.deadline.remaining()
            if remaining <= 0:
                break
            try:
                line = gw.log.get(timeout=remaining)
            except queue.Empty:
                break
            if line is None:
                raise coi.internal("canopend ended (exit %s)" % gw.proc.poll())
            doc = None
            m = RE_EMCY.search(line)
            if m:
                node = int(m.group(1), 16)
                bit, info = int(m.group(4), 16), int(m.group(5), 16)
                if node == args.node_id:
                    doc = coi.emcy_event(node, int(m.group(2), 16), int(m.group(3), 16),
                                         bytes([bit]) + info.to_bytes(4, "little"))
            m = RE_HB.search(line)
            if m and int(m.group(1), 16) == args.node_id:
                state = STATE_NAMES.get(m.group(2), m.group(2))
                doc = (coi.bootup_event(args.node_id) if state == "initialising"
                       else coi.heartbeat_event(args.node_id, state))
            if doc is not None:
                received += 1
                coi.emit(doc)

    with_gateway(args, run)
    complete = received >= args.count
    coi.emit(coi.result("listen", received=received, complete=complete))
    if not complete:
        raise coi.timeout("%d of %d events before the timeout" % (received, args.count))


# ── device: canopend-device ─────────────────────────────────────────────────

def emcy_register(error_bit):
    """The error register CANopenNode derives from one error status bit
    (CO_Emergency.h: CO_CONFIG_ERR_CONDITION_*)."""
    return {5: 0x01, 2: 0x10, 3: 0x10, 8: 0x80, 9: 0x80}.get(error_bit >> 3, 0x00)


def cmd_device(args, caps):
    env = dict(os.environ)
    if args.heartbeat_ms is not None:
        env["COI_HEARTBEAT_MS"] = str(args.heartbeat_ms)
    if args.tick_ms is not None:
        env["COI_TICK_MS"] = str(args.tick_ms)
    if args.serial is not None:
        env["COI_SERIAL"] = "0x%08X" % args.serial
    if args.dump:
        env["COI_DUMP"] = ",".join("%04X:%02X" % k for k in args.dump)
    if args.emcy is not None:
        code, register, data = args.emcy
        if len(data) != 5:
            raise coi.unsupported("CANopenNode's EMCY carries 5 bytes: error status bit and 32-bit info code")
        bit, info = data[0], int.from_bytes(data[1:5], "little")
        if bit >= 80 or emcy_register(bit) != register:
            raise coi.unsupported("CANopenNode derives the error register from the error status bit: bit 0x%02X "
                                  "gives register 0x%02X, not 0x%02X" % (bit, emcy_register(bit) if bit < 80 else 0,
                                                                        register))
        env["COI_EMCY"] = "%04X:%02X:%08X" % (code, bit, info)
        env["COI_EMCY_AFTER_MS"] = str(args.emcy_after_ms)
    if os.path.abspath(args.eds) != "/fixtures/eds/interop-device.eds":
        with open(args.eds, "rb") as f, open("/fixtures/eds/interop-device.eds", "rb") as g:
            if f.read() != g.read():
                raise coi.unsupported("canopend-device is built with the Object Dictionary of "
                                      "fixtures/eds/interop-device.eds; another EDS needs another build")

    stop = coi.Stop()
    deadline = coi.Deadline(args.timeout_ms)
    dumps, ready = {}, False
    node_id = args.node_id
    while True:
        out = queue.Queue()
        proc = subprocess.Popen(["canopend-device", args.interface, "-i", str(args.node_id)],
                                stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, env=env,
                                cwd="/tmp")
        threading.Thread(target=lines_of, args=(proc.stdout, out), daemon=True).start()
        ended, sent_term = False, False
        dumps = {}
        while not ended:
            if (stop.requested or deadline.expired()) and not sent_term:
                proc.send_signal(signal.SIGTERM)
                sent_term = True
            try:
                line = out.get(timeout=0.05)
            except queue.Empty:
                continue
            if line is None:
                ended = True
            elif line == "COI READY" and not ready:
                ready = True
                if args.node_id == coi.LSS_UNCONFIGURED:
                    coi.emit(coi.event("ready"))
                else:
                    coi.emit(coi.event("ready", node=args.node_id))
            elif line.startswith("COI NODEID "):
                nid = int(line[11:])
                if nid != node_id:  # an LSS-configured node-ID became active
                    node_id = nid
                    coi.emit(coi.event("node-id", node=nid))
            elif line.startswith("COI BITRATE "):
                kbps, delay = (int(x) for x in line[12:].split())
                coi.emit(coi.event("bit-rate", kbps=kbps, delayMs=delay))
            elif line.startswith("COI DUMP "):
                key, _, value = line[9:].partition(" ")
                idx, sub = key.split(":")
                dumps[coi.hex_key(int(idx, 16), int(sub, 16))] = None if value.startswith("ERR") else value
        code = proc.wait()
        # canopend ends by itself only on NMT reset node ("reset application").
        reset = not sent_term and code == 0
        if not ready:
            raise coi.interface_error("canopend-device ended (exit %d) before it booted" % code)
        if reset and not (stop.requested or deadline.expired()):
            node_id = args.node_id  # the power-on node-ID (LSS configuration in RAM is lost)
            continue  # NMT reset node: the device's program restarts (power cycle)
        break
    values = {coi.hex_key(i, s): dumps.get(coi.hex_key(i, s)) for i, s in args.dump}
    coi.emit(coi.result("device", node=args.node_id, values=values, nodeId=node_id))


